#!/usr/bin/env perl
# gs3d_drag_reference.pl — GS3D(段階 A)の姿勢の更新を、決まった入力の列に通して、
# 途中の姿勢(クォータニオン・zoom・透視かどうか)を C の配列として書き出す。
# giza-server の test/test_scene3d.c の、段階 B の gsp_scene3d_input との突き合わせの期待値に使う。
# ドラッグは GS3D の _apply_drag_rotation をそのまま呼び、ホイールとキー p・r は GS3D::run の
# 該当の行(zoom *= 1 + dzoom*0.1、p で透視を切り替え、r で qrot と zoom を戻す)と同じにする。
use strict; use warnings;
use PDL;
use PDL::Graphics::Cairo::Driver::GS3D;
my $d = PDL::Graphics::Cairo::Driver::GS3D->new(scene => { points => zeroes(1, 3) }, width => 400, height => 400);
my @inputs = map { input($_) } 1 .. 120;
my %check = map { $_ => 1 } 10, 39, 40, 41, 69, 70, 71, 120;
print "/* generated by gs3d_drag_reference.pl from PDL::Graphics::Cairo::Driver::GS3D */\n";
print "struct drag_step { float dx, dy, dzoom; uint8_t type, key; };\n";
print "static const struct drag_step drag_steps[] = {\n";
printf "    { %.6ff, %.6ff, %.6ff, %d, %d },\n", @{$_}{qw(dx dy dzoom type key)} for @inputs;
print "};\nstruct drag_check { int step; double q[4]; double zoom; int persp; };\n";
print "static const struct drag_check drag_checks[] = {\n";
for my $i (1 .. @inputs) {
    my $in = $inputs[$i - 1];
    # 送るのは float(GSP_MSG_3D_INPUT は f32)なので、Perl でも f32 に丸めた値を使う
    my ($dx, $dy, $dz) = unpack 'f<3', pack 'f<3', @{$in}{qw(dx dy dzoom)};
    $d->_apply_drag_rotation($dx, $dy);
    $d->{zoom} *= (1 + $dz * 0.1) if abs($dz) > 0.01;
    if ($in->{type} == 2) {
        if    (chr($in->{key}) =~ /^[pP]$/) { $d->{perspective} = !$d->{perspective} }
        elsif (chr($in->{key}) =~ /^[rR]$/) { $d->{qrot} = [0, 0, 0, 1]; $d->{zoom} = 1.0 }
    }
    next unless $check{$i};
    printf "    { %d, { %.9f, %.9f, %.9f, %.9f }, %.9f, %d },\n", $i, @{ $d->{qrot} }, $d->{zoom}, $d->{perspective} ? 1 : 0;
}
print "};\n";

# 決まった入力の列: ドラッグ(sin・cos で決める)、10 回ごとにホイール、40 回目に p、70 回目に r
sub input {
    my ($i) = @_;
    return { dx => 0, dy => 0, dzoom => 0, type => 2, key => ord('p') } if $i == 40;
    return { dx => 0, dy => 0, dzoom => 0, type => 2, key => ord('r') } if $i == 70;
    return { dx => 0, dy => 0, dzoom => ($i % 20 ? 0.5 : -0.7), type => 1, key => 0 } if $i % 10 == 0;
    return { dx => 7 * sin($i * 0.7) + 3, dy => 5 * cos($i * 1.3), dzoom => 0, type => 0, key => 0 };
}
